# ---------------------------------------------------------------------------------- instrumentation
class RecordingDict(dict):
    """dict that records which simulator module writes each key."""
    log = collections.defaultdict(set)      # (entity, prop) -> {writer}
    entity_id = None

    def _writer(self):
        f = sys._getframe(2)
        while f is not None:
            fn = f.f_code.co_filename.replace("\\", "/")
            if fn.startswith(SIM) and "/simulator/state/" not in fn:
                return fn[len(str(ROOT).replace("\\", "/")) + 1:]
            f = f.f_back
        return "unknown"

    def __setitem__(self, k, v):
        RecordingDict.log[(self.entity_id, k)].add(self._writer())
        super().__setitem__(k, v)

    def update(self, *a, **kw):
        w = self._writer()
        for k in dict(*a, **kw):
            RecordingDict.log[(self.entity_id, k)].add(w)
        super().update(*a, **kw)


_orig_register = state_mod.CanonicalState.register_entity


def _register(self, id, kind, name, properties=None, units=None, meta=None):
    rec = _orig_register(self, id, kind, name, properties, units, meta)
    if not isinstance(rec.properties, RecordingDict):
        rd = RecordingDict()
        rd.entity_id = id
        writer = rd._writer()
        for k in rec.properties:
            RecordingDict.log[(id, k)].add(writer)
        dict.update(rd, rec.properties)
        rec.properties = rd
    return rec


state_mod.CanonicalState.register_entity = _register


# ---------------------------------------------------------------------------------- helpers
def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in r) + " |")
    return "\n".join(out)


def write(path: Path, title: str, intro: str, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{HEADER}# {title}\n\n{intro.strip()}\n\n{body.strip()}\n", encoding="utf-8")
    print("wrote", path.relative_to(ROOT))


def dtype(v):
    if isinstance(v, bool):
        return "bool"
    if isinstance(v, (int, np.integer)) and not isinstance(v, bool):
        return "int"
    if isinstance(v, (float, np.floating)):
        return "float"
    if isinstance(v, str):
        return "string"
    if isinstance(v, list):
        return "list"
    if v is None:
        return "null"
    return type(v).__name__


