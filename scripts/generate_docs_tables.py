def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    sys.path.insert(0, str(ROOT / "scripts"))
    sc = ScenarioStore().load("SCN-COOL-001")
    e = SimulationEngine(sc, duration_override=3600 if args.quick else None)
    e.run()

    # which variables are read by whom
    readers = collections.defaultdict(set)
    for lid, d in cs.LOOPS.items():
        readers[f"XMEAS({d.pv})"].add(f"loop {d.tag}")
    for a in e.state.collection("alarms").values():
        src = a.definition.source
        if src.upper().startswith("XMEAS"):
            readers[catalog.normalize_id(src)].add(f"alarm {a.alarm_id}")
    for r in e.coupling.relations:
        for ref in r.inputs.values():
            if ref.kind == "process":
                readers[ref.a].add(f"relation {r.id}")
    for tests in e.config["quality"]["product_specifications"].values():
        for t in tests["tests"]:
            for v in t["inputs"].values():
                readers[catalog.normalize_id(v)].add(f"quality test {t['id']}")
    for mid, spec in e.config["materials"]["materials"].items():
        if spec.get("tep"):
            readers[catalog.normalize_id(spec["tep"]["measurement"])].add(f"inventory metering {mid}")
    readers[catalog.normalize_id(e.config["production"]["line"]["product_flow_measurement"])].add("production metering")

    # properties that can reach a TEP boundary parameter through the coupling graph (+ inventory logic)
    deps = collections.defaultdict(set)
    for r in e.coupling.relations:
        for ref in r.inputs.values():
            if ref.kind == "entity":
                deps[str(r.output)].add(f"{ref.a}.{ref.b}")
    for sid in e.inventory.storage:
        deps[f"{sid}.supply_availability"] |= {f"{sid}.quantity_kg", f"{sid}.usable_kg"}
    for aid in e.equipment.assets:
        deps[f"{aid}.is_running"] |= {f"{aid}.status", f"{aid}.health", f"{aid}.desired_state"}
    influence = set()
    stack = [f"tep.boundary.{n}" for n in BOUNDARY_PARAMETERS]
    while stack:
        x = stack.pop()
        for d in deps.get(x, ()):
            if d not in influence:
                influence.add(d)
                stack.append(d)

    events_by_target = collections.defaultdict(set)
    for ev in e.bus.log:
        if ev.target:
            events_by_target[ev.target].add(ev.type.value)

    gen_measurements(e, readers)
    gen_xmv(e, readers)
    gen_idv(e)
    gen_loops(e)
    gen_relations(e)
    gen_variable_reference(e, influence)
    gen_events(e, e.bus.log)
    gen_entity_table(e, events_by_target)
    if not args.quick:
        gen_demo_trace(e, e.history.query(e.history.series_names(), max_points=0))


if __name__ == "__main__":
    main()
