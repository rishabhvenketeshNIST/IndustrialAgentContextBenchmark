def gen_demo_trace(e, series):
    t = np.array(series["time"])
    s = series["series"]

    def arr(k):
        return np.array([np.nan if v is None else v for v in s[k]], dtype=float)
    T9, X10, P7 = arr("TRUE:XMEAS(9)"), arr("XMV(10)"), arr("TRUE:XMEAS(7)")
    cap = arr("UT-CW-REACTOR.capacity_fraction")
    h = arr("WU-CWP-101A.health")
    sat = t[X10 >= 99.9]
    from simulator.common import fmt_hms
    kp = [["Reactor T before fault (mean 0-1 h, true)", f"{np.nanmean(T9[t < 3600]):.2f} degC"],
          ["Peak reactor T (true)", f"{np.nanmax(T9):.2f} degC at {fmt_hms(t[np.nanargmax(T9)])}"],
          ["Minimum reactor T after recovery (true)", f"{np.nanmin(T9[t > 6400]):.2f} degC at "
                                                      f"{fmt_hms(t[t > 6400][np.nanargmin(T9[t > 6400])])}"],
          ["Peak reactor pressure (true)", f"{np.nanmax(P7):.0f} kPa gauge (trip at 3000)"],
          ["XMV(10) before fault", f"{np.nanmean(X10[t < 3600]):.1f} %"],
          ["XMV(10) at 100 % (trend samples, 10 s)", f"{fmt_hms(sat.min())} to {fmt_hms(sat.max())}" if len(sat) else "never"],
          ["Minimum UT-CW-REACTOR capacity fraction", f"{np.nanmin(cap):.3f}"],
          ["Minimum P-101A health", f"{np.nanmin(h):.3f}"],
          ["Process shutdown", str(e.state.process.shutdown)]]
    skip = {"MATERIAL_CONSUMED", "QUALITY_SAMPLE_TAKEN"}
    rows = []
    for ev in e.bus.log:
        if ev.type.value in skip:
            continue
        p = ev.payload
        detail = p.get("message") or p.get("new") or p.get("status") or p.get("description") or p.get("reason") or ""
        if p.get("failing_tests"):
            detail = f"FAIL {p['failing_tests']}"
        rows.append([ev.event_id, fmt_hms(ev.simulation_time), ev.type.value, ev.source, ev.target or "",
                     str(detail)[:70], ev.correlation_id, ev.visibility.value])
    intro = f"""Observed trace of `scenarios/SCN-COOL-001.yaml` (seed {e.scenario['seed']}, backend
{e.adapter.backend_name}), produced by running the scenario. `run_id` {e.state.run['run_id']}.
Key values come from the 10-second in-memory trend buffer (true process values). The event list omits
the periodic `MATERIAL_CONSUMED` and `QUALITY_SAMPLE_TAKEN` events. The narrative explanation is in
docs/06_scenarios/causal_chains.md and docs/MASTER_SIMULATOR_SPEC.md."""
    body = "## Key values\n\n" + md_table(["Quantity", "Value"], kp) + "\n\n## Event log\n\n" + md_table(
        ["Id", "Time", "Type", "Source", "Target", "Detail", "Correlation", "Visibility"], rows)
    write(DOCS / "06_scenarios" / "scenario_examples" / "SCN-COOL-001_trace.md", "SCN-COOL-001 observed trace",
          intro, body)


