def classify_prop(e, eid, prop, writers, influence):
    ent = e.state.entity(eid)
    meta = ent.meta
    b_x = e.mapping.resolve_property(eid, prop)
    if b_x and b_x.startswith("XMEAS"):
        return "measured", "observation of TEP (transmitted value)"
    if b_x and b_x.startswith("XMV"):
        return "commanded", "TEP manipulated variable (copy)"
    if prop in ("process_value",):
        return "measured", "observation of TEP (transmitted PV)"
    if prop in ("setpoint", "output", "mode"):
        return "commanded", "native controller state (copy)"
    if prop == "saturated":
        return "derived", "enterprise interpretation of controller output"
    if prop.startswith(("rated_", "nominal_")) or prop in ("capacity", "capacity_kg", "material", "unit",
                                                             "category", "tep_measurement"):
        return "constant", "configuration"
    if prop == "vibration":
        return "measured", "observable condition-monitoring indicator (derived from health)"
    if prop.endswith("_deviation"):
        return "derived", "simulation truth (lot composition deviation incl. fault effect); NOT tagged unobservable"
    if prop == "efficiency" and not any(w.startswith("CouplingEngine") for w in writers):
        return "constant", "placeholder 1.0 set at setup; no relation updates it"
    if any(w.startswith("CouplingEngine") for w in writers):
        return "derived", "enterprise simulation (causal relation)"
    if prop in meta.get("model_internal", []) or prop in ("health",):
        return "simulated", "simulation truth (model-internal)"
    if prop in meta.get("unobservable", []):
        return "simulated", "simulation truth (physical, not instrumented)"
    if prop in ("status", "availability", "role", "desired_state", "last_result", "consecutive_failures",
                "last_result_fail", "level_pct") or prop.endswith("_pct"):
        return "derived", "enterprise interpretation"
    return "simulated", "enterprise simulation state"


def gen_variable_reference(e, influence):
    groups = collections.OrderedDict()
    for (eid, prop), ws in sorted(RecordingDict.log.items()):
        if eid not in e.state.entities or prop not in e.state.entities[eid].properties:
            continue
        ent = e.state.entity(eid)
        cls = ent.meta.get("asset_type") or ent.meta.get("equipment_class") or ent.meta.get("utility_type") or ent.kind
        section = {"utility": "Utility services", "material": "Materials"}.get(ent.kind)
        if section is None:
            if eid.startswith("SU-"):
                section = "Storage units"
            elif ent.meta.get("asset"):
                section = "Maintainable assets (equipment condition and capability)"
            elif e.mapping.resolve_property(eid, prop) or cls in ("pid_loop",):
                section = "Process-bound equipment properties (TEP observations and control)"
            else:
                section = "Other equipment / enterprise properties"
        key = (section, cls, prop)
        g = groups.setdefault(key, {"entities": [], "writers": set(), "units": set(), "types": set()})
        g["entities"].append(eid)
        g["writers"] |= {WRITER_LABEL.get(w, w) for w in ws}
        if ent.units.get(prop):
            g["units"].add(ent.units[prop])
        g["types"].add(dtype(ent.properties[prop]))
    by_section = collections.OrderedDict()
    for (section, cls, prop), g in groups.items():
        eid0 = g["entities"][0]
        kind, truth = classify_prop(e, eid0, prop, g["writers"], influence)
        infl = "yes" if any(f"{x}.{prop}" in influence for x in g["entities"]) else "no"
        ent = e.state.entity(eid0)
        hidden = prop in ent.meta.get("unobservable", [])
        internal = prop in ent.meta.get("model_internal", [])
        vis = "yes (`/api/entities`)" + ("; hidden in UI/`/api/inventory`" if hidden else "") + \
              ("; tagged model_internal" if internal else "")
        ents = ", ".join(g["entities"][:6]) + (f" (+{len(g['entities']) - 6})" if len(g["entities"]) > 6 else "")
        upd = "; ".join(sorted(g["writers"]))
        by_section.setdefault(section, []).append(
            [f"`{prop}`", cls, ents, ", ".join(sorted(g["units"])) or "-", "/".join(sorted(g["types"])), upd,
             kind, truth, infl, vis])
    body = []
    for section, rows in by_section.items():
        body.append(f"## {section}\n\n" + md_table(
            ["Property", "Class", "Entities", "Unit", "Type", "Written by (observed)", "Kind", "Truth / interpretation",
             "Influences TEP", "Agent-visible (current API)"], rows))
    intro = """Every entity property present in the canonical state (`CanonicalState.entities`) during the
SCN-COOL-001 demonstration, grouped by entity class. **Written by** is *observed*: the generator runs
the scenario with instrumented property dictionaries and records the module that performed each write,
so it reflects actual behaviour, not intent.

* **Kind**: measured (TEP measurement copy), commanded (setpoint / XMV / mode), derived (computed from
  other variables), simulated (state evolved by a module), constant (configuration).
* **Influences TEP**: "yes" when the property is an input, directly or transitively, of a coupling
  relation that writes a `tep.boundary.*` parameter, or of inventory supply availability which does.
* **Agent-visible (current API)**: there is no agent interface yet; this column states what the
  operational REST API returns. Every property is returned by `/api/entities/{id}`; metadata tags
  (`model_internal`, `unobservable`) label but do not filter (see docs/11_limitations/documentation_vs_implementation.md).
* TEP process variables (XMEAS, XMV, setpoints) are documented in docs/03_tep; process image fields in
  docs/05_state_and_events/canonical_state.md."""
    write(DOCS / "05_state_and_events" / "variable_reference.md", "Enterprise variable reference", intro,
          "\n\n".join(body))


def gen_events(e, demo_log):
    emitters = collections.defaultdict(set)
    for p in (ROOT / "simulator").rglob("*.py"):
        rel = str(p.relative_to(ROOT)).replace("\\", "/")
        if rel.endswith("events/__init__.py"):
            continue
        for m in re.finditer(r"EventType\.([A-Z_]+)", p.read_text(encoding="utf-8")):
            emitters[m.group(1)].add(rel)
    for p in (ROOT / "api").rglob("*.py"):
        for m in re.finditer(r"EventType\.([A-Z_]+)", p.read_text(encoding="utf-8")):
            emitters[m.group(1)].add(str(p.relative_to(ROOT)).replace("\\", "/"))
    counts = collections.Counter(ev.type.value for ev in demo_log)
    keys = collections.defaultdict(set)
    for ev in demo_log:
        keys[ev.type.value] |= set(ev.payload)
    rows = []
    for t in EventType:
        rows.append([t.value, "benchmark" if t in BENCHMARK_EVENT_TYPES else "operational",
                     "LC-" if t.value in ("SIMULATION_STARTED", "SIMULATION_PAUSED", "SIMULATION_RESUMED",
                                          "SIMULATION_RESET") else "EV-",
                     "<br>".join(sorted(emitters.get(t.name, []))) or "**never emitted**",
                     counts.get(t.value, 0), ", ".join(sorted(keys.get(t.value, []))) or "-"])
    intro = """All event types in `simulator/events/__init__.py` (`EventType`). *Referenced in* is a static scan
of the source for `EventType.<NAME>` (publishers and subscribers). *Demo count* and *payload keys* are
observed in a full SCN-COOL-001 run. Visibility is `benchmark` for `BENCHMARK_EVENT_TYPES`; lifecycle
events use the separate `LC-` id sequence."""
    write(DOCS / "05_state_and_events" / "event_catalog.md", "Event catalog (reference table)", intro,
          md_table(["Type", "Visibility", "Id prefix", "Referenced in", "Demo count", "Payload keys observed"], rows))


